import fs from 'node:fs';
import assert from 'node:assert/strict';
const html=fs.readFileSync(new URL('../../index.html',import.meta.url),'utf8');
let tests=0;const ok=(v,m)=>{tests++;assert.ok(v,m)};
const marker='V99 · PERFIL PÚBLICO CENTRAL DAS UNIDADES',i=html.indexOf(marker),block=i>=0?html.slice(i):'';
ok(i>=0,'bloco administrativo do perfil público existe');
ok(block.includes("/api/v1/config/units/")&&block.includes("/public-profile"),'admin lê e salva perfil pelo backend central');
ok(block.includes("page==='unit-profile'")||block.includes("page==='unitPublicProfile'"),'perfil possui página administrativa própria');
ok(block.includes('Horário de funcionamento'),'interface apresenta horários da unidade');
ok(block.includes('Não informado'),'horário desconhecido possui estado próprio');
ok(block.includes('Copiar para outros dias'),'há conveniência para copiar horário');
ok(block.includes('Exibir esta unidade no site'),'visibilidade é editável');
ok(block.includes('@media(max-width:720px)'),'formulário possui adaptação para celular');
ok(!block.includes('localStorage.setItem'),'perfil central não é salvo em localStorage');
ok(!html.includes('5531983514216'),'WhatsApp real não fica hardcoded no frontend');
ok(!html.includes('em frente à Leitura'),'referência do Big não fica hardcoded no frontend');
ok(!html.includes('em frente à TIM'),'referência do Shopping não fica hardcoded no frontend');
ok(!html.includes('Caixa d’Água'),'referência do Centro não fica hardcoded no frontend');

const publicMarker='V99 · PUBLIC BOOKING CENTRAL CATALOG',pi=html.indexOf(publicMarker),publicBlock=pi>=0?html.slice(pi,html.indexOf('V99 · PERFIL PÚBLICO CENTRAL DAS UNIDADES',pi)):'';
ok(pi>=0,'ponte pública central existe');
ok(publicBlock.includes("/api/v1/public/units"),'cartões públicos consultam GET /api/v1/public/units');
ok(publicBlock.includes("publicUnitsCache"),'unidades públicas possuem cache separado do seed local');
ok(publicBlock.includes("p.publicName||u.name||u.id"),'nome público vem do perfil central');
ok(publicBlock.includes("p.openingStatus")&&publicBlock.includes("Horário não informado"),'status público usa openingStatus e fallback seguro');
ok(publicBlock.includes("p.fullAddress"),'endereço público vem do perfil central');
ok(publicBlock.includes("p.locationHint"),'orientação pública vem do perfil central');
const unitRender=publicBlock.slice(publicBlock.indexOf("let uh=document.getElementById('publicUnits')"),publicBlock.indexOf("async function refreshHome"));
ok(!unitRender.includes("(db.units||[])"),'cartões públicos não usam db.units/seed');
ok(unitRender.includes("directionsUrl=typeof p.directionsUrl==='string'?p.directionsUrl.trim():''"),'Como chegar usa directionsUrl vindo do perfil público do backend');
ok(unitRender.includes("whatsappUrl=typeof p.whatsappUrl==='string'?p.whatsappUrl.trim():''"),'WhatsApp usa whatsappUrl vindo do perfil público do backend');
ok(unitRender.includes("bookingEnabled=bookingCatalog?.bookingEnabled===true"),'estado de agendamento do cartão respeita bookingEnabled do catálogo central');
ok(unitRender.includes("bookingAction=bookingEnabled?")&&unitRender.includes('Agendar nesta unidade')&&unitRender.includes('Agendamento indisponível'),'ação Agendar nesta unidade só aparece quando bookingEnabled está ativo');
ok(unitRender.includes('v99-public-unit-directions')&&unitRender.includes('Como chegar'),'cartão público renderiza Como chegar somente com URL válida');
ok(unitRender.includes('v99-public-unit-whatsapp')&&unitRender.includes('WhatsApp'),'cartão público renderiza WhatsApp somente com URL válida');

console.log(JSON.stringify({ok:true,tests,feature:'unit_public_profile_admin_ui_contract'}));
